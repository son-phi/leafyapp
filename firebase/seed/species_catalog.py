def validate():
    labels = [s["aiLabel"] for s in SPECIES]
    assert len(labels) == len(set(labels)), "aiLabel trùng"
    ids = [s["id"] for s in SPECIES]
    assert len(ids) == len(set(ids)), "id trùng"
    legacy = [s["legacyId"] for s in SPECIES if s["legacyId"] is not None]
    assert len(legacy) == len(set(legacy)) == 29, "legacyId phải đủ 29 và không trùng"
    for s in SPECIES:
        t = s["threshold"]
        for a, b in (("soilMoistureMin", "soilMoistureMax"), ("temperatureMin", "temperatureMax"),
                     ("airHumidityMin", "airHumidityMax"), ("lightMin", "lightMax")):
            assert t[a] < t[b], f"{s['id']}: {a} >= {b}"
        assert t["soilMoistureCritical"] < t["soilMoistureMin"], f"{s['id']}: critical >= min"
        assert s["lightNeed"] in LIGHT_NEED_VI, s["id"]
        assert s["careLevel"] in ("EASY", "MEDIUM", "HARD"), s["id"]
        for c in s["careTemplates"]:
            assert c["taskType"] in ("WATERING", "FERTILIZING", "PRUNING", "SPRAYING", "HEALTH_CHECK", "OTHER")
            assert c["repeatIntervalDays"] > 0
    return len(SPECIES)
