def th(soil, temp, hum, light):
    c, mn, mx = soil
    return {
        "soilMoistureCritical": c, "soilMoistureMin": mn, "soilMoistureMax": mx,
        "temperatureMin": temp[0], "temperatureMax": temp[1],
        "airHumidityMin": hum[0], "airHumidityMax": hum[1],
        "lightMin": light[0], "lightMax": light[1],
    }


def tpl(task_type, days, title, note):
    return {"taskType": task_type, "repeatIntervalDays": days, "title": title, "note": note}


def base_templates(water_days, water_note, fert_days, fert_note, check_days=14):
    out = [tpl("WATERING", water_days, "Tưới nước", water_note)]
    if fert_days:
        out.append(tpl("FERTILIZING", fert_days, "Bón phân", fert_note))
    out.append(tpl("HEALTH_CHECK", check_days, "Kiểm tra sức khỏe cây", HEALTH_CHECK_NOTE))
    return out


